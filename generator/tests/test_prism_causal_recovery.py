def test_two_tier_protocol_specification_in_spec_18():
    """Invariant 5: spec/18 defines both protocol_fast and protocol_full with sound window math."""
    spec_18_path = _find_spec_dir() / "18_benchmark_reporting.yaml"
    assert spec_18_path.exists()
    spec_18 = yaml.safe_load(spec_18_path.read_text(encoding="utf-8"))

    protocols = spec_18.get("evaluation_protocols", {})
    assert "protocol_fast" in protocols, "protocol_fast missing from spec/18"
    assert "protocol_full" in protocols, "protocol_full missing from spec/18"

    fast = protocols["protocol_fast"]
    full = protocols["protocol_full"]

    # Protocol Fast Window Math
    fast_warmup = fast["w_train_days"] + fast["delta_delay_days"]
    assert fast_warmup == 4.5
    assert fast["time_span_days"] == 12.0
    fast_windows = int(np.floor((fast["time_span_days"] - fast_warmup) / fast["w_test_days"]))
    assert 5 <= fast_windows <= 8, f"protocol_fast test windows {fast_windows} outside [5, 8]"

    # Protocol Full Window Math
    full_warmup = full["w_train_days"] + full["delta_delay_days"]
    assert full_warmup == 44.0
    assert full["time_span_days"] >= 75.0
    full_windows = int(np.floor((full["time_span_days"] - full_warmup) / full["w_test_days"]))
    assert full_windows >= 16, f"protocol_full test windows {full_windows} below 16"


